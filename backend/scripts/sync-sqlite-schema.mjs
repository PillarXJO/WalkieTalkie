#!/usr/bin/env node
// Syncs prisma/sqlite/schema.prisma from prisma/schema.prisma so a local
// SQLite development profile stays available. The schema is written to be
// provider-portable, so this only needs to swap the datasource provider.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url)) + '/..';
const canonical = `${root}/prisma/schema.prisma`;
const sqlite = `${root}/prisma/sqlite/schema.prisma`;

let schema = readFileSync(canonical, 'utf8');

if (!/provider\s*=\s*"postgresql"/.test(schema)) {
  throw new Error('schema.prisma does not contain a postgresql provider; refusing to sync');
}

schema = schema.replace(
  'provider = "postgresql"',
  'provider = "sqlite"',
);
schema = schema.replace(
  'url      = env("DATABASE_URL")',
  'url      = env("SQLITE_DATABASE_URL")',
);
schema = schema.replace(
  /^(\/\/ ---.*)$/m,
  '// GENERATED by scripts/sync-sqlite-schema.mjs from the canonical\n// prisma/schema.prisma. Do not edit by hand. Please edit the canonical file.\n\n$1',
);

mkdirSync(dirname(sqlite), { recursive: true });
writeFileSync(sqlite, schema, 'utf8');
console.log(`Wrote ${sqlite}`);